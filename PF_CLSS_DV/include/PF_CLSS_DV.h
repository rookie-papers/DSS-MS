#ifndef PF_CLSS_DV_H
#define PF_CLSS_DV_H

#include "Tools.h"
#include <string>
#include <vector>
#include <tuple>

using namespace std;

namespace PF_CLSS_DV {
    extern csprng rng;
    extern gmp_randstate_t state_gmp;

    // =====================================================================
    // Data Structures
    // =====================================================================

    // System public parameters for PF-CLSS-DV scheme
    struct Params {
        mpz_class q;      // The order of the elliptic curve group
        ECP P;            // The generator of the elliptic curve group G
        ECP Q_pub;        // KGC's public key (Q_pub = sP)
    };

    // Master secret key held by the Key Generation Center (KGC)
    struct MasterKey {
        mpz_class s;      // The master key s ∈ Z_q^*
    };

    // Key pair for the designated verifier
    struct VerifierKey {
        mpz_class SK_V;   // Verifier's private key (x_V ∈ Z_q^*)
        ECP PK_V;         // Verifier's public key (x_V * P ∈ G)
    };

    // Signer's partial key generated by the KGC
    struct PartialKey {
        ECP R;            // R = rP ∈ G
        mpz_class d;      // d = r + s * Hf_1(ID_O, R) ∈ Z_q^*
    };

    // Signer's public key
    struct SignerPubKey {
        ECP R;            // From partial key
        ECP X_O;          // X_O = x_O * P ∈ G
    };

    // Signer's private key
    struct SignerPrivKey {
        mpz_class d;      // From partial key
        mpz_class x_O;    // Random value x_O ∈ Z_q^*
    };

    // Message structure (divided into data blocks)
    // Here customized for two blocks: e.g., m1 (sanitizable) and m2 (fixed)
    struct Message {
        string m1;
        string m2;
    };

    // Certificateless sanitizable signature over the message blocks
    struct Signature {
        mpz_class u1;     // Signature component for block 1 (∈ Z_q^*)
        mpz_class u2;     // Signature component for block 2 (∈ Z_q^*)
        ECP T1;           // Signature component for block 1 (∈ G)
        ECP T2;           // Signature component for block 2 (∈ G)
    };

    // Authorization token generated by the signer for the sanitizer
    struct AuthToken {
        mpz_class AT1;    // Token enabling modification of the sanitizable block
    };

    // =====================================================================
    // appendToOctet hooks for custom structs (required for HashToZp)
    // =====================================================================

    inline void appendToOctet(octet* hash, const SignerPubKey& pk) {
        hash_recursive(hash, pk.R, pk.X_O);
    }

    inline void appendToOctet(octet* hash, const Message& msg) {
        hash_recursive(hash, msg.m1, msg.m2);
    }

    // =====================================================================
    // Safe modular arithmetic helpers
    // =====================================================================

    inline mpz_class mod_sub(const mpz_class& a, const mpz_class& b, const mpz_class& q) {
        return (((a - b) % q) + q) % q;
    }

    // =====================================================================
    // Core Algorithm Declarations
    // =====================================================================

    /**
     * @brief Initialize system public parameters and master secret key.
     * * This algorithm is executed by the KGC. It inputs a security parameter $1^{\lambda}$ and exports the system parameters param and a master key msk. [cite: 180]
     * * @return tuple<Params, MasterKey> The system parameters and master key.
     */
    tuple<Params, MasterKey> Setup();

    /**
     * @brief Generate the designated verifier's key pair.
     * * This algorithm is executed by the designated verifier. [cite: 181]
     * * @param pp The system public parameters.
     * @return VerifierKey The designated verifier's private and public key pair.
     */
    VerifierKey VerKeyGen(Params pp);

    /**
     * @brief Generate a partial key for a signer.
     * * This algorithm is executed by the KGC. [cite: 183] It relies on the master key to bind the signer's identity.
     * * @param pp The system public parameters.
     * @param msk The KGC's master secret key.
     * @param ID_O The identity string of the original signer.
     * @return PartialKey The partial key (R, d) for the signer.
     */
    PartialKey PartialKeyGen(Params pp, MasterKey msk, string ID_O);

    /**
     * @brief Generate the full private and public key pair for the signer.
     * * This algorithm is executed by the signer. [cite: 185]
     * * @param pp The system public parameters.
     * @param ID_O The identity string of the original signer.
     * @param pak The partial key obtained from the KGC.
     * @return tuple<SignerPubKey, SignerPrivKey> The complete key pair for the signer.
     */
    tuple<SignerPubKey, SignerPrivKey> SinKeyGen(Params pp, string ID_O, PartialKey pak);

    /**
     * @brief Generate a signature and authorization token over the message.
     * * This algorithm is executed by the signer. [cite: 187] The signature is specifically bound to the designated verifier's public key.
     * * @param pp The system public parameters.
     * @param ID_O The identity string of the original signer.
     * @param SK_O The signer's private key.
     * @param M The original message containing blocks.
     * @param PK_V The public key of the designated verifier.
     * @return tuple<Signature, AuthToken> The generated signature and the authorization token for the sanitizer.
     */
    tuple<Signature, AuthToken> Sign(Params pp, string ID_O, SignerPrivKey SK_O, Message M, ECP PK_V);

    /**
     * @brief Alter sensitive message blocks and recreate a valid signature.
     * * This algorithm is executed by the sanitizer. [cite: 189]
     * * @param pp The system public parameters.
     * @param ID_O The identity string of the original signer.
     * @param M The original signed message.
     * @param sig The original signature.
     * @param at The authorization token provided by the signer.
     * @param m1_prime The new, sanitized content for block 1.
     * @return tuple<Message, Signature> The sanitized message and the newly adapted signature.
     */
    tuple<Message, Signature> Sanitize(Params pp, string ID_O, Message M, Signature sig, AuthToken at, string m1_prime);

    /**
     * @brief Verify a signature (either original or sanitized).
     * * This algorithm is executed by the designated verifier. [cite: 191]
     * * @param pp The system public parameters.
     * @param ID_O The identity string of the signer.
     * @param PK_O The public key of the signer.
     * @param VK_V The private and public key structure of the designated verifier.
     * @param M_star The message to be verified (original or sanitized).
     * @param sig_star The corresponding signature.
     * @return true If the signature is valid.
     * @return false If the signature is invalid.
     */
    bool Verify(Params pp, string ID_O, SignerPubKey PK_O, VerifierKey VK_V, Message M_star, Signature sig_star);

} // namespace PF_CLSS_DV

#endif // PF_CLSS_DV_H